"""The lock and constraints sync check that CI runs (NFR1.6)."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

ROOT = Path(__file__).resolve().parents[1]


def load_script() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "check_constraints", ROOT / "scripts" / "check_constraints.py"
    )
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["check_constraints"] = module
    spec.loader.exec_module(module)
    return module


check = load_script()

LOCK = """
version = 1
[[package]]
name = "telethon"
version = "1.45.0"
[[package]]
name = "pytest_asyncio"
version = "1.4.1.post1"
"""


def test_comments_and_blank_lines_do_not_count() -> None:
    exported = "# generated by uv\ntelethon==1.45.0\n    # via telegram-mcp\n\nrsa==4.9.1\n"
    committed = "# a different header\ntelethon==1.45.0\nrsa==4.9.1  # via telethon\n"
    assert check.compare_export(exported, committed) == []


def test_a_drifted_or_missing_constraint_is_reported() -> None:
    problems = check.compare_export("telethon==1.45.0\nrsa==4.9.1\n", "telethon==1.44.0\n")
    assert problems == [
        "constraints.txt lacks: telethon==1.45.0",
        "constraints.txt lacks: rsa==4.9.1",
        "constraints.txt has extra: telethon==1.44.0",
    ]


def test_pins_must_be_exact_and_equal_the_lock() -> None:
    pyproject = """
[project]
dependencies = ["telethon==1.45.0", "mcp>=2"]
[dependency-groups]
dev = ["pytest-asyncio==1.4.0"]
"""
    assert check.check_pins(pyproject, LOCK) == [
        "not pinned with ==: mcp>=2",
        "pytest-asyncio==1.4.0 but uv.lock has 1.4.1.post1",
    ]


def test_this_repository_is_in_sync() -> None:
    assert (
        check.check_pins((ROOT / "pyproject.toml").read_text(), (ROOT / "uv.lock").read_text())
        == []
    )
    assert check.main(ROOT) == 0
